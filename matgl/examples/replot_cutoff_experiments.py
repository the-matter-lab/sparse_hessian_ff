#!/usr/bin/env python3
"""
Replot sparse Hessian cutoff experiment figures from saved NPZ files.

This script mirrors the plots generated by `sparse_hessian_cutoff_real.py`,
including wall-time vs cutoff, error vs wall time, and eigenvalue mean-error vs wall time
(all with optional naive reference lines on the time-axis figures),
and x-axis ordering for HVP sweeps — but uses the unified method colors shared
with the other experiment plots and labels the eigenvalue-error axes with the
actual error formulas used. Timing data are read from `timings_s_*` and
`naive_hessian_time_s` in the plot-series NPZ, with fallback to the matching
`cutoff_debug_data_*.npz` when present.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

# Matches the unified colors used in the other experiment replots.
COLORS = {
    "naive": "#4e79a7",
    "star": "#f28e2b",
    "acyclic": "#59a14f",
    "distance_two": "#b07aa1",
}
COLORS_LIGHT = {
    "naive": "#a0c4e8",
    "star": "#f6c98c",
    "acyclic": "#9fcd8f",
    "distance_two": "#d4b3d4",
}
MARKERS = {
    "naive": "o",
    "star": "s",
    "acyclic": "^",
    "distance_two": "D",
}

LABEL_FS = int(round(14 * 1.3))
LEGEND_FS = int(round(12 * 1.4))
TICK_FS = 16
LINEWIDTH = 4.5
REF_LINEWIDTH = 2.0
MARKERSIZE = 10
LINE_FIGSIZE = (10, 6)
RESULTS_ROOT = Path(__file__).resolve().parent / "sparse_hessian_results" / "cutoff_experiments"

def _timestamp_from_name(name: str) -> str | None:
    match = re.search(r"_(\d{8}_\d{6})(?:\.[^.]+)?$", name)
    return match.group(1) if match else None


def _eigenval_first_keys(z: np.lib.npyio.NpzFile) -> dict[str, str]:
    keys = {}
    for key in z.files:
        match = re.match(r"eigenval_errors_first(\d+)_(.+)$", key)
        if match:
            keys[match.group(2)] = key
    return keys


def _mean_rel_err_label(n_terms: int | None = None) -> str:
    if n_terms is None:
        return (
            r"$\frac{1}{N_{\mathrm{eig}}}\sum_i"
            r"\frac{|\lambda_i-\lambda_i^{\mathrm{GT}}|}{|\lambda_i^{\mathrm{GT}}|}$"
        )
    return (
        rf"$\frac{{1}}{{{n_terms}}}\sum_{{i=1}}^{{{n_terms}}}"
        r"\frac{|\lambda_i-\lambda_i^{\mathrm{GT}}|}{|\lambda_i^{\mathrm{GT}}|}$"
    )


def _pointwise_rel_err_label() -> str:
    return r"$\frac{|\lambda_i-\lambda_i^{\mathrm{GT}}|}{|\lambda_i^{\mathrm{GT}}|}$"


def _savefig(path: Path) -> None:
    plt.tight_layout()
    plt.savefig(path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"  wrote {path.name}")


def _style_current_ticks() -> None:
    plt.xticks(fontsize=TICK_FS)
    plt.yticks(fontsize=TICK_FS)


def _style_axis_ticks(ax) -> None:
    ax.tick_params(axis="both", labelsize=TICK_FS)


def _finite_sorted_by_x(
    x: np.ndarray, y: np.ndarray, extra_mask: np.ndarray | None = None
) -> tuple[np.ndarray, np.ndarray]:
    """Keep finite (x, y); optionally extra_mask; return pairs sorted by x (stable)."""
    x_arr = np.asarray(x, dtype=float)
    y_arr = np.asarray(y, dtype=float)
    mask = np.isfinite(x_arr) & np.isfinite(y_arr)
    if extra_mask is not None:
        mask &= np.asarray(extra_mask, dtype=bool)
    x_m, y_m = x_arr[mask], y_arr[mask]
    if x_m.size == 0:
        return x_m, y_m
    order = np.argsort(x_m, kind="stable")
    return x_m[order], y_m[order]


def _naive_wall_time_s(z: np.lib.npyio.NpzFile, debug_dz: np.lib.npyio.NpzFile | None) -> float | None:
    if "naive_hessian_time_s" in z.files:
        v = float(z["naive_hessian_time_s"].flat[0])
        if np.isfinite(v) and v > 0:
            return v
    if debug_dz is not None and "naive_hessian_time_s" in debug_dz.files:
        v = float(debug_dz["naive_hessian_time_s"].flat[0])
        if np.isfinite(v) and v > 0:
            return v
    return None


def _timings_for_alg(
    z: np.lib.npyio.NpzFile, debug_dz: np.lib.npyio.NpzFile | None, alg: str
) -> np.ndarray | None:
    key = f"timings_s_{alg}"
    if key in z.files:
        return np.asarray(z[key], dtype=float)
    if debug_dz is not None and key in debug_dz.files:
        return np.asarray(debug_dz[key], dtype=float)
    return None


def replot_cutoff(series_path: Path, suffix: str) -> None:
    z = np.load(series_path, allow_pickle=True)
    cutoffs = np.asarray(z["cutoffs"], dtype=float)
    algorithms = [str(a) for a in z["algorithms"]]
    full_rows = int(z["full_hessian_rows"].flat[0])
    label_fs = LABEL_FS
    legend_fs = LEGEND_FS
    eig_first_keys = _eigenval_first_keys(z)
    n_first = 10
    for key in eig_first_keys.values():
        match = re.match(r"eigenval_errors_first(\d+)_", key)
        if match:
            n_first = int(match.group(1))
            break

    timestamp = str(z["timestamp"].flat[0]) if "timestamp" in z.files else _timestamp_from_name(series_path.name) or "unknown"
    out_dir = series_path.parent
    debug_path = out_dir / f"cutoff_debug_data_{timestamp}.npz"
    debug_dz = np.load(debug_path, allow_pickle=True) if debug_path.is_file() else None
    naive_wall_s = _naive_wall_time_s(z, debug_dz)

    def color(alg: str) -> str:
        return COLORS.get(alg, "#666666")

    def marker(alg: str) -> str:
        return MARKERS.get(alg, "o")

    # 1) Error vs cutoff
    plt.figure(figsize=LINE_FIGSIZE)
    for alg in algorithms:
        key = f"errors_{alg}"
        if key not in z.files:
            continue
        values = np.asarray(z[key], dtype=float)
        mask = np.isfinite(values) & (values > 0)
        if np.any(mask):
            plt.plot(
                cutoffs[mask],
                values[mask],
                marker=marker(alg),
                color=color(alg),
                linewidth=LINEWIDTH,
                markersize=MARKERSIZE,
                label=alg.replace("_", " ").title(),
            )
    plt.xlabel("Cutoff Radius (Angstroms)", fontsize=label_fs)
    plt.ylabel("Max Absolute Error vs Naive", fontsize=label_fs)
    plt.legend(fontsize=legend_fs)
    plt.grid(True, alpha=0.3)
    plt.yscale("log", nonpositive="mask")
    _style_current_ticks()
    _savefig(out_dir / f"cutoff_error_comparison_{timestamp}{suffix}.png")

    # 2) HVPs vs cutoff
    plt.figure(figsize=LINE_FIGSIZE)
    for alg in algorithms:
        key = f"n_hvps_{alg}"
        if key not in z.files:
            continue
        values = np.asarray(z[key], dtype=float)
        mask = np.isfinite(values)
        if np.any(mask):
            plt.plot(
                cutoffs[mask],
                values[mask],
                marker=marker(alg),
                color=color(alg),
                linewidth=LINEWIDTH,
                markersize=MARKERSIZE,
                label=alg.replace("_", " ").title(),
            )
    plt.axhline(full_rows, color=COLORS["naive"], linestyle="--", linewidth=REF_LINEWIDTH, label="Full Hessian rows")
    plt.xlabel("Cutoff Radius (Angstroms)", fontsize=label_fs)
    plt.ylabel("Number of Hessian-Vector Products", fontsize=label_fs)
    plt.legend(fontsize=legend_fs)
    plt.grid(True, alpha=0.3)
    _style_current_ticks()
    _savefig(out_dir / f"cutoff_hvp_comparison_{timestamp}{suffix}.png")

    # 2b) Wall time vs cutoff (matches sparse_hessian_cutoff_real.py plot 2b)
    plt.figure(figsize=LINE_FIGSIZE)
    wrote_timings = False
    for alg in algorithms:
        t_vals = _timings_for_alg(z, debug_dz, alg)
        if t_vals is None:
            continue
        mask = t_vals > 0
        xc, yt = _finite_sorted_by_x(cutoffs, t_vals, mask)
        if xc.size == 0:
            continue
        wrote_timings = True
        plt.plot(
            xc,
            yt,
            marker=marker(alg),
            color=color(alg),
            linewidth=LINEWIDTH,
            markersize=MARKERSIZE,
            label=alg.replace("_", " ").title(),
        )
    if naive_wall_s is not None:
        plt.axhline(
            naive_wall_s,
            color=COLORS["naive"],
            linestyle="--",
            linewidth=REF_LINEWIDTH,
            label="Naive reference time",
        )
    plt.xlabel("Cutoff Radius (Angstroms)", fontsize=label_fs)
    plt.ylabel("Wall Time per Hessian (s)", fontsize=label_fs)
    plt.legend(fontsize=legend_fs)
    plt.grid(True, alpha=0.3)
    _style_current_ticks()
    if wrote_timings or naive_wall_s is not None:
        _savefig(out_dir / f"cutoff_wall_time_comparison_{timestamp}{suffix}.png")
    else:
        plt.close()
        print(
            "  skipped cutoff_wall_time_comparison (no timings_s_* in series/debug NPZ; re-run experiment or use newer dump)"
        )

    # 3-4) Eigenvalue errors vs cutoff
    for key_type, ylabel, out_name in (
        ("first", _mean_rel_err_label(n_first), "cutoff_eigenval_comparison"),
        ("all", _mean_rel_err_label(), "cutoff_eigenval_all_comparison"),
    ):
        plt.figure(figsize=LINE_FIGSIZE)
        for alg in algorithms:
            if key_type == "first":
                key = eig_first_keys.get(alg) or f"eigenval_errors_first{n_first}_{alg}"
            else:
                key = f"eigenval_errors_all_{alg}"
            if key not in z.files:
                continue
            values = np.asarray(z[key], dtype=float)
            mask = np.isfinite(values) & (values > 0)
            if np.any(mask):
                plt.plot(
                    cutoffs[mask],
                    values[mask],
                    marker=marker(alg),
                    color=color(alg),
                    linewidth=LINEWIDTH,
                    markersize=MARKERSIZE,
                    label=alg.replace("_", " ").title(),
                )
        plt.xlabel("Cutoff Radius (Angstroms)", fontsize=label_fs)
        plt.ylabel(ylabel, fontsize=label_fs)
        plt.legend(fontsize=legend_fs)
        plt.grid(True, alpha=0.3)
        plt.yscale("log", nonpositive="mask")
        _style_current_ticks()
        _savefig(out_dir / f"{out_name}_{timestamp}{suffix}.png")

    # 5-7) Metrics vs HVP count
    for metric, ylabel, out_name in (
        ("errors", "Max Absolute Error vs Naive", "error_vs_hvp_comparison"),
        ("eigenval_first", _mean_rel_err_label(n_first), "eigenval_vs_hvp_comparison"),
        ("eigenval_all", _mean_rel_err_label(), "eigenval_all_vs_hvp_comparison"),
    ):
        plt.figure(figsize=LINE_FIGSIZE)
        for alg in algorithms:
            x_key = f"n_hvps_{alg}"
            if x_key not in z.files:
                continue
            x_vals = np.asarray(z[x_key], dtype=float)
            if metric == "errors":
                y_vals = np.asarray(z[f"errors_{alg}"], dtype=float)
            elif metric == "eigenval_first":
                y_key = eig_first_keys.get(alg) or f"eigenval_errors_first{n_first}_{alg}"
                if y_key not in z.files:
                    continue
                y_vals = np.asarray(z[y_key], dtype=float)
            else:
                y_key = f"eigenval_errors_all_{alg}"
                if y_key not in z.files:
                    continue
                y_vals = np.asarray(z[y_key], dtype=float)
            mask = np.isfinite(x_vals) & np.isfinite(y_vals) & (y_vals > 0)
            xh, yh = _finite_sorted_by_x(x_vals, y_vals, mask)
            if xh.size > 0:
                plt.plot(
                    xh,
                    yh,
                    marker=marker(alg),
                    color=color(alg),
                    linewidth=LINEWIDTH,
                    markersize=MARKERSIZE,
                    label=alg.replace("_", " ").title(),
                )
        plt.axvline(full_rows, color=COLORS["naive"], linestyle="--", linewidth=REF_LINEWIDTH, label="Full Hessian rows")
        plt.xlabel("Number of Hessian-Vector Products", fontsize=label_fs)
        plt.ylabel(ylabel, fontsize=label_fs)
        plt.legend(fontsize=legend_fs)
        plt.grid(True, alpha=0.3)
        plt.yscale("log", nonpositive="mask")
        _style_current_ticks()
        _savefig(out_dir / f"{out_name}_{timestamp}{suffix}.png")

    # 7b) Max error vs wall time (x sorted by time; log-y only if any positive error)
    plt.figure(figsize=LINE_FIGSIZE)
    ax_te = plt.gca()
    min_positive_error: float | None = None
    wrote_err_time_curves = False
    for alg in algorithms:
        t_vals = _timings_for_alg(z, debug_dz, alg)
        if t_vals is None or f"errors_{alg}" not in z.files:
            continue
        err_vals = np.asarray(z[f"errors_{alg}"], dtype=float)
        mask = (err_vals > 0) & np.isfinite(err_vals) & (t_vals > 0) & np.isfinite(t_vals)
        xt, ye = _finite_sorted_by_x(t_vals, err_vals, mask)
        if xt.size == 0:
            continue
        wrote_err_time_curves = True
        plt.plot(
            xt,
            ye,
            marker=marker(alg),
            color=color(alg),
            linewidth=LINEWIDTH,
            markersize=MARKERSIZE,
            label=alg.replace("_", " ").title(),
        )
        mp = float(np.min(ye))
        min_positive_error = mp if min_positive_error is None else min(min_positive_error, mp)
    if naive_wall_s is not None:
        plt.axvline(
            naive_wall_s,
            color=COLORS["naive"],
            linestyle="--",
            linewidth=REF_LINEWIDTH,
            label="Naive reference time",
        )
    plt.xlabel("Wall Time per Hessian (s)", fontsize=label_fs)
    plt.ylabel("Max Absolute Error vs Naive", fontsize=label_fs)
    plt.legend(fontsize=legend_fs)
    plt.grid(True, alpha=0.3)
    if min_positive_error is not None:
        ax_te.set_ylim(bottom=max(min_positive_error * 0.5, 1e-30))
        plt.yscale("log", nonpositive="mask")
    else:
        ax_te.text(
            0.5,
            0.5,
            "No positive max-error points\n(all exact or missing data);\nsee wall time vs cutoff plot.",
            transform=ax_te.transAxes,
            ha="center",
            va="center",
            fontsize=label_fs,
        )
    _style_current_ticks()
    if wrote_err_time_curves or naive_wall_s is not None:
        _savefig(out_dir / f"error_vs_time_comparison_{timestamp}{suffix}.png")
    else:
        plt.close()
        print(
            "  skipped error_vs_time_comparison (no timings/errors to plot; re-run experiment or use newer dump)"
        )

    def _eigenval_vs_time_figure(
        y_key_for_alg,
        out_stem: str,
        ylabel: str,
        skip_reason: str,
    ) -> None:
        plt.figure(figsize=LINE_FIGSIZE)
        ax = plt.gca()
        min_pos: float | None = None
        wrote = False
        for alg in algorithms:
            t_vals = _timings_for_alg(z, debug_dz, alg)
            if t_vals is None:
                continue
            y_key = y_key_for_alg(alg)
            if y_key is None or y_key not in z.files:
                continue
            y_vals = np.asarray(z[y_key], dtype=float)
            mask = (y_vals > 0) & np.isfinite(y_vals) & (t_vals > 0) & np.isfinite(t_vals)
            xt, yy = _finite_sorted_by_x(t_vals, y_vals, mask)
            if xt.size == 0:
                continue
            wrote = True
            plt.plot(
                xt,
                yy,
                marker=marker(alg),
                color=color(alg),
                linewidth=LINEWIDTH,
                markersize=MARKERSIZE,
                label=alg.replace("_", " ").title(),
            )
            mp = float(np.min(yy))
            min_pos = mp if min_pos is None else min(min_pos, mp)
        if naive_wall_s is not None:
            plt.axvline(
                naive_wall_s,
                color=COLORS["naive"],
                linestyle="--",
                linewidth=REF_LINEWIDTH,
                label="Naive reference time",
            )
        plt.xlabel("Wall Time per Hessian (s)", fontsize=label_fs)
        plt.ylabel(ylabel, fontsize=label_fs)
        plt.legend(fontsize=legend_fs)
        plt.grid(True, alpha=0.3)
        if min_pos is not None:
            ax.set_ylim(bottom=max(min_pos * 0.5, 1e-30))
            plt.yscale("log", nonpositive="mask")
        else:
            ax.text(
                0.5,
                0.5,
                "No positive mean eigenvalue-error points\n(all exact or missing data).",
                transform=ax.transAxes,
                ha="center",
                va="center",
                fontsize=label_fs,
            )
        _style_current_ticks()
        if wrote or naive_wall_s is not None:
            _savefig(out_dir / f"{out_stem}_{timestamp}{suffix}.png")
        else:
            plt.close()
            print(f"  skipped {out_stem} ({skip_reason})")

    # 7c) Mean eigenvalue relative error (first N) vs wall time
    _eigenval_vs_time_figure(
        lambda alg: eig_first_keys.get(alg) or f"eigenval_errors_first{n_first}_{alg}",
        "eigenval_vs_time_comparison",
        _mean_rel_err_label(n_first),
        "no timings / eigenval series to plot",
    )

    # 7d) Mean eigenvalue relative error (all modes) vs wall time
    _eigenval_vs_time_figure(
        lambda alg: f"eigenval_errors_all_{alg}",
        "eigenval_all_vs_time_comparison",
        _mean_rel_err_label(),
        "no timings / eigenval_all series to plot",
    )

    # 8) Per-eigenvalue error bars
    fig, axes = plt.subplots(2, len(algorithms), figsize=(20, 10))
    if len(algorithms) == 1:
        axes = np.array([[axes[0]], [axes[1]]])

    eigvals_naive = None
    if debug_dz is not None and "eigvals_naive_eckart_projected_sorted" in debug_dz.files:
        eigvals_naive = np.asarray(debug_dz["eigvals_naive_eckart_projected_sorted"], dtype=float)

    for col_idx, alg in enumerate(algorithms):
        key = f"per_eig_errors_all_{alg}"
        ax_top = axes[0, col_idx]
        ax_bottom = axes[1, col_idx]
        if key not in z.files:
            ax_top.text(0.5, 0.5, "No data", ha="center", va="center", transform=ax_top.transAxes)
            ax_bottom.text(0.5, 0.5, "No data", ha="center", va="center", transform=ax_bottom.transAxes)
            continue

        matrix = np.asarray(z[key], dtype=float)
        representative_idx = None
        for i in range(matrix.shape[0] - 1, -1, -1):
            row = matrix[i]
            if np.any(np.isfinite(row) & (row >= 0)):
                representative_idx = i
                break

        if representative_idx is None:
            ax_top.text(0.5, 0.5, "No valid run", ha="center", va="center", transform=ax_top.transAxes)
            ax_bottom.text(0.5, 0.5, "No valid run", ha="center", va="center", transform=ax_bottom.transAxes)
            continue

        errors = matrix[representative_idx]
        finite = errors[np.isfinite(errors)]
        top_cap = float(np.percentile(finite, 99.5)) if finite.size else 1e-12
        top_cap = max(top_cap, 1e-12)
        errors_plot = np.clip(errors, 0.0, top_cap)
        eig_indices = np.arange(len(errors_plot))

        ax_top.bar(
            eig_indices,
            errors_plot,
            width=0.9,
            color=color(alg),
            alpha=0.92,
            edgecolor="white",
            linewidth=0.4,
        )
        ax_top.set_ylim(0.0, top_cap * 1.05)
        ax_top.grid(True, alpha=0.3, axis="y")
        if col_idx == 0:
            ax_top.set_ylabel(_pointwise_rel_err_label(), fontsize=label_fs)
        ax_top.set_xlabel("Eigenvalue Index", fontsize=label_fs)
        ax_top.set_title(f"{alg.replace('_', ' ').title()} (cutoff={cutoffs[representative_idx]:.0f} Å)", fontsize=label_fs - 1)
        _style_axis_ticks(ax_top)

        if eigvals_naive is not None and len(eigvals_naive) == len(errors_plot):
            eig_span = float(np.max(eigvals_naive) - np.min(eigvals_naive))
            bar_width = eig_span / max(len(eigvals_naive) * 1.5, 1)
            if not np.isfinite(bar_width) or bar_width <= 0:
                bar_width = 1e-3
            ax_bottom.bar(
                eigvals_naive,
                errors_plot,
                width=bar_width,
                color=COLORS_LIGHT.get(alg, color(alg)),
                alpha=0.92,
                edgecolor="white",
                linewidth=0.4,
            )
        ax_bottom.set_ylim(0.0, top_cap * 1.05)
        ax_bottom.grid(True, alpha=0.3, axis="y")
        if col_idx == 0:
            ax_bottom.set_ylabel(_pointwise_rel_err_label(), fontsize=label_fs)
        ax_bottom.set_xlabel("Ground-Truth Eigenvalue", fontsize=label_fs)
        _style_axis_ticks(ax_bottom)

    plt.tight_layout(rect=[0, 0, 1, 0.96])
    out_path = out_dir / f"per_eigenvalue_error_bars_{timestamp}{suffix}.png"
    plt.savefig(out_path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"  wrote {out_path.name}")

    if debug_dz is not None:
        debug_dz.close()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--series",
        type=Path,
        default=None,
        help="Path to a specific cutoff_plot_series_*.npz file. Defaults to the latest one in cutoff_experiments.",
    )
    parser.add_argument(
        "--results-root",
        type=Path,
        default=RESULTS_ROOT,
        help="Directory containing cutoff_plot_series_*.npz files.",
    )
    parser.add_argument(
        "--suffix",
        default="_unified_colors_replot",
        help="Suffix inserted before .png for regenerated plots.",
    )
    args = parser.parse_args()

    suffix = args.suffix if args.suffix.startswith("_") else f"_{args.suffix}"

    if args.series is not None:
        series_path = args.series
    else:
        candidates = sorted(args.results_root.glob("cutoff_plot_series_*.npz"))
        if not candidates:
            raise SystemExit(f"No cutoff_plot_series_*.npz found in {args.results_root}")
        series_path = candidates[-1]

    print(f"Replotting cutoff experiments from {series_path}")
    replot_cutoff(series_path, suffix)
    print("Done.")


if __name__ == "__main__":
    main()
